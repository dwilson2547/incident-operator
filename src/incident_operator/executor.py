"""The executor (docs/design.md §7.2): `python -m incident_operator executor`, its own Deployment and ServiceAccount.

It takes `ready` fix runs from Postgres one at a time and performs them with a small fixed set of verbs. It reads the
operation from its own copy of the operation files, never from the database: a run row names an operation, its
revision and its parameters, and the executor refuses a run whose revision isn't the loaded one or whose parameters
aren't plain names in the operation's own namespaces. Its RBAC is generated by the chart from the same files, so
even a forged row can do no more than a committed operation allows.

Env: DATABASE_URL, OPERATIONS_DIR; KUBE_API_URL for local runs.
"""
from __future__ import annotations

import logging
import os
import time

from . import db
from .evidence import K8s
from .fixes import valid_params
from .library import Library, Operation
from .ops import _fill

log = logging.getLogger("incident_operator.executor")


def delete_pods(k8s: K8s, run: dict) -> str:
    ns = run["namespace"]
    q = {"labelSelector": ",".join(f"{k}={v}" for k, v in run["selector"].items())}
    if run.get("node"):
        q["fieldSelector"] = f"spec.nodeName={run['node']}"
    pods = k8s.get(f"/api/v1/namespaces/{ns}/pods", q)["items"]
    limit = run.get("maxPods", 1)
    if not pods:
        raise RuntimeError(f"no pods match {q} in {ns}")
    if len(pods) > limit:                         # a selector that matches more than intended stops here
        raise RuntimeError(f"{len(pods)} pods match {q} in {ns}, more than maxPods={limit}: nothing deleted")
    names = [p["metadata"]["name"] for p in pods]
    for name in names:
        k8s.delete(f"/api/v1/namespaces/{ns}/pods/{name}")
    return f"deleted pod{'s' if len(names) > 1 else ''} {', '.join(f'{ns}/{n}' for n in names)}"


def create_job_from(k8s: K8s, run: dict, run_id: int) -> str:
    """What `kubectl create job --from=cronjob/<name>` does: the CronJob's job template, owned by the CronJob."""
    ns, cj_name = run["namespace"], run["cronjob"]
    cj = k8s.get(f"/apis/batch/v1/namespaces/{ns}/cronjobs/{cj_name}")
    tmpl = cj["spec"]["jobTemplate"]
    name = f"{cj_name[:40]}-io-{run_id}"
    job = {"apiVersion": "batch/v1", "kind": "Job",
           "metadata": {"name": name, "namespace": ns,
                        "labels": (tmpl.get("metadata") or {}).get("labels") or {},
                        "annotations": {**((tmpl.get("metadata") or {}).get("annotations") or {}),
                                        "cronjob.kubernetes.io/instantiate": "manual",
                                        "incident-operator/fix-run": str(run_id)},
                        "ownerReferences": [{"apiVersion": "batch/v1", "kind": "CronJob", "name": cj_name,
                                             "uid": cj["metadata"]["uid"], "controller": True}]},
           "spec": tmpl["spec"]}
    k8s.post(f"/apis/batch/v1/namespaces/{ns}/jobs", job)
    return f"created job {ns}/{name} from cronjob/{cj_name}"


def perform(k8s: K8s, op: Operation, params: dict, run_id: int) -> str:
    run = _fill(op.run, valid_params(op, params))
    if run["verb"] == "DeletePods":
        return delete_pods(k8s, run)
    if run["verb"] == "CreateJobFrom":
        return create_job_from(k8s, run, run_id)
    raise RuntimeError(f"unknown verb {run['verb']}")


def step(conn, library: Library, k8s: K8s) -> int:
    library.refresh()
    run = db.claim_ready(conn)
    if run is None:
        return 0
    op = library.operations.get(run["operation"])
    try:
        if op is None or not op.mutating:
            raise RuntimeError(f"{run['operation']} isn't a loaded mutating operation")
        if op.rev != run["op_rev"]:
            raise RuntimeError(f"{op.name} changed since it was approved ({run['op_rev']} -> {op.rev})")
        result = perform(k8s, op, run["params"], run["id"])
    except Exception as e:
        log.warning("fix run %s (%s) failed: %s", run["id"], run["operation"], e)
        db.update_op_run(conn, run["id"], "failed", error=f"{type(e).__name__}: {e}"[:500])
        return 1
    db.update_op_run(conn, run["id"], "settling", result=result, settle_seconds=op.settle_seconds)
    log.info("fix run %s (%s): %s; post-checks in %ss", run["id"], op.name, result, op.settle_seconds)
    return 1


def main() -> int:
    logging.basicConfig(level=os.environ.get("LOG_LEVEL", "INFO"),
                        format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    logging.getLogger("httpx").setLevel(logging.WARNING)
    conn = db.connect(os.environ["DATABASE_URL"])
    library = Library(None, os.environ.get("OPERATIONS_DIR", "/etc/incident-operator/operations"))
    k8s = K8s(base=os.environ["KUBE_API_URL"]) if os.environ.get("KUBE_API_URL") else K8s()
    log.info("executor: watching for ready fix runs")
    while True:
        try:
            if step(conn, library, k8s) == 0:
                time.sleep(3)
        except Exception:
            log.exception("executor pass failed")
            time.sleep(5)
